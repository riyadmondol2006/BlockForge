"""Pack the per-version dumps written by tools/convert/dump/Dump.java into data/convert/*.z.

Usage: post.py <dumps-dir> <chunker-clone> <out-dir> [--verify]

Each dump directory holds the full table for one version (a version threshold). Rows that are identical across
consecutive versions are merged into `since`/`until` form; an I row (input -> pivot) and its mirror C row
(pivot -> input) become one B row. Every output file is zlib-compressed text whose first lines are comments.
--verify re-expands the packed files and compares them with every dump (lossless check).
"""
import subprocess
import sys
import zlib
from collections import defaultdict
from pathlib import Path


def vkey(v):
    return tuple(int(x) for x in v.split("."))


def read_lines(path):
    if not path.exists():
        return None
    text = path.read_text(encoding="utf-8")
    return [l for l in text.split("\n") if l != ""]


def intervals(idx_set, versions):
    """Runs of consecutive version indices -> (since, until) strings ('' = open)."""
    out = []
    idxs = sorted(idx_set)
    i = 0
    while i < len(idxs):
        j = i
        while j + 1 < len(idxs) and idxs[j + 1] == idxs[j] + 1:
            j += 1
        since = "" if idxs[i] == 0 else versions[idxs[i]]
        until = "" if idxs[j] + 1 >= len(versions) else versions[idxs[j] + 1]
        out.append((since, until))
        i = j + 1
    return out


def header(commit, what):
    return [
        "# Derived from Chunker (https://github.com/HiveGamesOSS/Chunker), Copyright (c) 2024 Hive Games, MIT License.",
        "# Chunker commit %s" % commit,
        "# %s; generated by tools/convert/post.py from tools/convert/dump/Dump.java output, do not edit" % what,
    ]


def write_z(path, lines):
    data = ("\n".join(lines) + "\n").encode("utf-8")
    path.write_bytes(zlib.compress(data, 9))
    return len(data), path.stat().st_size


def merge_kinds(per_version, versions, mirror):
    """per_version: list (by version index) of sets of ('I'|'C', fields...). Returns rows for packing.

    A row is (kind, fields) where fields is the neutral tuple. I and C rows with equal neutral tuples are folded into B
    wherever both are present."""
    present = defaultdict(lambda: {"I": set(), "C": set()})
    for vi, rows in enumerate(per_version):
        for kind, fields in rows:
            present[fields][kind].add(vi)
    out = []
    for fields in sorted(present):
        p = present[fields]
        both = p["I"] & p["C"] if mirror else set()
        for kind, s in (("B", both), ("I", p["I"] - both), ("C", p["C"] - both)):
            for since, until in intervals(s, versions):
                out.append((kind, since, until, fields))
    return out


def neutral_block_row(line):
    """Dump line -> (kind, neutral tuple (id, ins, type, outs, group)); None for X rows."""
    f = line.split("\t")
    if f[0] == "I":
        return "I", (f[1], f[2], f[3], f[4], f[5])
    if f[0] == "C":  # type, pivot-ins, id, outs, group -> mirror of the I row
        return "C", (f[3], f[4], f[1], f[2], f[5])
    raise ValueError(line)


def neutral_item_row(line):
    f = line.split("\t")
    if f[0] == "I":
        return "I", (f[1], f[2], f[3], f[4])
    if f[0] == "C":
        return "C", (f[3], f[4], f[1], f[2])
    raise ValueError(line)


def pack_rows(edition, table, dumps, versions, commit, neutral):
    per_version, extra = [], defaultdict(set)
    for vi, v in enumerate(versions):
        lines = read_lines(dumps / edition / v / (table + ".tsv"))
        rows = set()
        for l in lines or []:
            if l.startswith("X\t"):
                extra[l.split("\t")[1]].add(vi)
            else:
                rows.add(neutral(l))
        per_version.append(rows)
    out = []
    for g in sorted(extra):
        for since, until in intervals(extra[g], versions):
            out.append("X\t%s\t%s\t%s" % (since, until, g))
    for kind, since, until, f in merge_kinds(per_version, versions, True):
        out.append("\t".join([kind, since, until] + list(f)))
    return out


def pack_simple(edition, dumps, versions):
    names = sorted({p.name[len("simple_"):-4] for v in versions for p in (dumps / edition / v).glob("simple_*.tsv")})
    out = []
    for name in names:
        present = defaultdict(set)
        for vi, v in enumerate(versions):
            for l in read_lines(dumps / edition / v / ("simple_%s.tsv" % name)) or []:
                present[l].add(vi)
        for l in sorted(present):
            f = l.split("\t")
            for since, until in intervals(present[l], versions):
                out.append("\t".join([name, f[0], since, until] + f[1:]))
    return out


def pack_groups(edition, dumps):
    """groups.tsv / types.tsv hold multi-line records `G name` / `T name` followed by body lines."""
    out = []
    for kind, fname in (("G", "groups.tsv"), ("T", "types.tsv")):
        lines = read_lines(dumps / edition / fname)
        recs, cur = [], None
        for l in lines:
            if l.startswith(kind + "\t"):
                cur = [l]
                recs.append(cur)
            else:
                cur.append(l)
        for rec in sorted(recs, key=lambda r: r[0]):
            if kind == "T":
                rec = fold_type(rec)
            out.extend(rec)
    return out


def fold_type(rec):
    """Fold M (in -> out) + R (in -> out) rows that agree into a single B row."""
    m = {tuple(l.split("\t")[1:]) for l in rec if l.startswith("M\t")}
    r = {tuple(l.split("\t")[1:]) for l in rec if l.startswith("R\t")}
    out = [l for l in rec if not l.startswith(("M\t", "R\t"))]
    out += ["B\t%s\t%s" % x for x in sorted(m & r)]
    out += ["M\t%s\t%s" % x for x in sorted(m - r)]
    out += ["R\t%s\t%s" % x for x in sorted(r - m)]
    return out


def pack_pivot(dumps):
    return read_lines(dumps / "pivot_states.tsv") + read_lines(dumps / "pivot_types.tsv")


# ---- verification ---------------------------------------------------------------------------------------------

def in_force(v, since, until):
    return (since == "" or vkey(v) >= vkey(since)) and (until == "" or vkey(v) < vkey(until))


def expand_rows(lines, v, ncols_neutral):
    """Packed row lines -> set of (kind, fields) in force at v with B expanded into I and C."""
    rows = set()
    for l in lines:
        if l.startswith("#"):
            continue
        f = l.split("\t")
        if f[0] == "X":
            if in_force(v, f[1], f[2]):
                rows.add(("X", (f[3],)))
            continue
        if in_force(v, f[1], f[2]):
            for k in ("I", "C") if f[0] == "B" else (f[0],):
                rows.add((k, tuple(f[3:])))
    return rows


def verify(out, dumps, versions, edition, commit):
    import zlib as z

    def load(name):
        return z.decompress((out / name).read_bytes()).decode().split("\n")

    def section(name, sec):
        lines, cur, res = load(name), None, []
        for l in lines:
            if l.startswith("@"):
                cur = l[1:]
            elif l and not l.startswith("#") and cur == sec:
                res.append(l)
        return res

    for table, neutral, fname, sec in (("blocks", neutral_block_row, "blocks", None),
                                       ("items", neutral_item_row, "items", None),
                                       ("legacy_blocks", neutral_block_row, "legacy", "blocks"),
                                       ("legacy_items", neutral_item_row, "legacy", "items")):
        fname = "%s_%s.z" % (edition, fname)
        if sec is None:
            lines = [l for l in load(fname) if l]
        else:
            lines = section(fname, sec)
        for v in versions:
            expect = set()
            for l in read_lines(dumps / edition / v / (table + ".tsv")) or []:
                if l.startswith("X\t"):
                    expect.add(("X", (l.split("\t")[1],)))
                else:
                    kind, fields = neutral(l)
                    expect.add((kind, fields))
            got = expand_rows(lines, v, 0)
            if got != expect:
                raise SystemExit("verify failed: %s %s %s (%d vs %d rows)" % (edition, table, v, len(got), len(expect)))
    # simple tables
    simple = [l for l in load("%s_misc.z" % edition) if l and not l.startswith("#")]
    for v in versions:
        expect = set()
        for p in (dumps / edition / v).glob("simple_*.tsv"):
            name = p.name[len("simple_"):-4]
            for l in read_lines(p):
                f = l.split("\t")
                expect.add(tuple([name, f[0]] + f[1:]))
        got = set()
        for l in simple:
            f = l.split("\t")
            if in_force(v, f[2], f[3]):
                got.add(tuple([f[0], f[1]] + f[4:]))
        if got != expect:
            raise SystemExit("verify failed: %s simple %s" % (edition, v))
    print("verified %s: %d versions" % (edition, len(versions)))


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    dumps, chunker, out = Path(args[0]), Path(args[1]), Path(args[2])
    commit = subprocess.check_output(["git", "-C", str(chunker), "rev-parse", "HEAD"], text=True).strip()
    out.mkdir(parents=True, exist_ok=True)
    total = 0
    sizes = []

    def emit(name, what, lines):
        nonlocal total
        raw, comp = write_z(out / name, header(commit, what) + lines)
        total += comp
        sizes.append((name, raw, comp))

    emit("pivot.z", "pivot (Chunker block types and states): S field name default values / T type states",
         pack_pivot(dumps))
    for edition in ("java", "bedrock"):
        versions = sorted((p.name for p in (dumps / edition).iterdir() if p.is_dir()), key=vkey)
        emit("%s_blocks.z" % edition,
             "%s block rows: B|I|C since until id input-states pivot-type pivot-states group; X since until group"
             % edition, pack_rows(edition, "blocks", dumps, versions, commit, neutral_block_row))
        emit("%s_items.z" % edition, "%s item rows: B|I|C since until id input-states type props" % edition,
             pack_rows(edition, "items", dumps, versions, commit, neutral_item_row))
        emit("%s_legacy.z" % edition, "%s legacy (numeric data) block%s rows" % (edition, " and item" if edition == "java" else ""),
             ["@blocks"] + pack_rows(edition, "legacy_blocks", dumps, versions, commit, neutral_block_row)
             + (["@items"] + pack_rows(edition, "legacy_items", dumps, versions, commit, neutral_item_row)
                if edition == "java" else []))
        emit("%s_groups.z" % edition, "%s state mapping groups (G) and type mappings (T)" % edition,
             pack_groups(edition, dumps))
        emit("%s_misc.z" % edition, "%s id tables: table kind since until key value" % edition,
             pack_simple(edition, dumps, versions))
        if "--verify" in sys.argv:
            verify(out, dumps, versions, edition, commit)
    for name, raw, comp in sizes:
        print("%-22s %9d -> %8d" % (name, raw, comp))
    print("total compressed: %d bytes" % total)


main()
