/// The `minecraft:` identifier of a banner pattern (`patterns[].pattern`, 1.20.5+).
pub fn banner_pattern_id(pattern: BannerPattern, version: Version) -> Option<&'static str> {
    BANNER_PATTERNS.iter().rev().find(|(gate, p, _)| *p == pattern && applies(*gate, version)).map(|row| row.2)
}

/// The short code of a banner pattern (`Patterns[].Pattern`, before 1.20.5).
pub fn banner_short_name(pattern: BannerPattern) -> Option<&'static str> {
    BANNER_SHORT_NAMES.iter().find(|(p, _)| *p == pattern).map(|row| row.1)
}

/// The identifier of an effect; `minecraft:empty` when the version does not know it (Chunker logs and uses that).
pub fn effect_name(effect: EffectType, version: Version) -> &'static str {
    EFFECT_NAMES
        .iter()
        .rev()
        .find(|(gate, e, _)| *e == effect && applies(*gate, version))
        .map_or("minecraft:empty", |row| row.2)
}

/// The numeric id of an effect (before 1.20.2); 0 when the version does not know it.
pub fn effect_id(effect: EffectType, version: Version) -> i32 {
    EFFECT_IDS.iter().rev().find(|(gate, e, _)| *e == effect && applies(*gate, version)).map_or(0, |row| row.2)
}

/// The entity id of an entity type for a version. Custom types keep their identifier.
pub fn entity_type_id(entity: &EntityType, version: Version) -> Option<String> {
    match entity {
        EntityType::Custom(id) => Some(id.to_string()),
        EntityType::Vanilla(vanilla) => ENTITY_TYPES
            .iter()
            .rev()
            .find(|(gate, e, _)| e == vanilla && applies(*gate, version))
            .map(|row| row.2.to_owned()),
    }
}
